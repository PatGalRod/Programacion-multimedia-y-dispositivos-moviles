// Muestra la suma, resta, multiplicación y división de dos enteros largos prefijados,
// así como el resto de dividir el primero entre el segundo.

fun main() {
    val n1 : Long = 5987345398555L
    val n2 : Long = 1234345723434L

    println("Suma ${n1 + n2}")
    println("Resta ${n1 - n2}")
    println( "Multiplicación ${n1 * n2}")
    println("División ${n1 / n2}")
    println("Resto ${n1 % n2}")
}
